/**
 * 基本数据类型：
 * 整型：
 * 1.byte     1字节
 * 2.short    2字节
 * 3.int      4字节
 * 4.long     8字节
 * 浮点型：
 * 1.float    4字节
 * 2.double   8字节
 * 字符型：
 * 1.char     2字节
 * 布尔型：
 * 1.boolean  1字节
 */
public class DataTypeEight {
    public static void main(String[] args) {
        byte a = 2;
        System.out.println(a);

        short b = 3;
        System.out.println(b);

        int c = 5;
        System.out.println(c);

        long d = 100L;
        System.out.println(d);

        float e = 3.14f;
        System.out.println(e);

        double f = 5.20;
        System.out.println(f);

        char ch = 'A';
        System.out.println(ch);

        boolean flag = true;
        System.out.println(flag);
    }
}
